BWOBuildings.GetRandomResidenceId = function()
    return BanditUtils.Choice(residenceIds)
end

BWOBuildings.IsResidence = function(building)
    local def = building:getDef()
    local id = string.format("%.0f", def:getID())
    for _, sid in ipairs(residenceIds) do
        if id == sid then return true end
    end
    return false
end

BWOBuildings.UpdateCache = function()
    local cache = {}
    local defs = getWorld():getMetaGrid():getBuildings()
    for i=0, defs:size()-1 do
        local def = defs:get(i)
        local id = string.format("%.0f", def:getID())
        local x = (def:getX() + def:getX2()) / 2
        local y = (def:getY() + def:getY2()) / 2
        cache[id] = {x=x, y=y}
    end
    BWOBuildings.cache = cache
end

local function onGameStart()
    BWOBuildings.UpdateCache()
end

Events.OnGameStart.Remove(onGameStart)
Events.OnGameStart.Add(onGameStart)